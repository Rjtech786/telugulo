async function uploadImage() {
  try {
    const res = await fetch(WP_IMAGE);
    if (!res.ok) throw new Error("HTTP " + res.status);
    const buf = Buffer.from(await res.arrayBuffer());
    const path = `${SLUG}.jpg`;
    const { error } = await supabase.storage
      .from("article-images")
      .upload(path, buf, { contentType: "image/jpeg", upsert: true });
    if (error) throw error;
    const { data } = supabase.storage.from("article-images").getPublicUrl(path);
    console.log("  image uploaded to Supabase ✓");
    return data.publicUrl;
  } catch (e) {
    console.log("  image upload failed (" + e.message + "), using WP url");
    return WP_IMAGE;
  }
}

async function main() {
  // default author
  let { data: author } = await supabase.from("authors").select("id").limit(1).maybeSingle();
  const authorId = author?.id ?? null;

  console.log("Importing Kalonji article…");
  const imageUrl = await uploadImage();

  const { data, error } = await supabase
    .from("articles")
    .upsert(
      {
        slug: SLUG,
        title: TITLE,
        title_meta: "కలోంజీ 10 ఆరోగ్య ప్రయోజనాలు | Kalonji Seeds in Telugu",
        meta_description: META,
        summary: SUMMARY,
        body: BODY,
        category: "lifestyle",
        image_url: imageUrl,
        author_id: authorId,
        status: "published",
        published_at: new Date().toISOString(),
        source_urls: [{ source: "WordPress migration", url: "https://telugulo.in/kalonji-seeds-in-telugu/" }],
      },
      { onConflict: "slug" },
    )
    .select("id, slug, status")
    .single();

  if (error) {
    console.error("FAILED:", error.message);
    process.exit(1);
  }
  console.log(`✓ Imported: /${data.slug}/ (${data.status})`);
}

